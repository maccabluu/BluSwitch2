// BluSwitch data folder stays in the app, not Eden-labelled DocumentsUI.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const js=fs.readFileSync('bluswitch-ui/app.js','utf8');
const actions=fs.readFileSync('bluswitch-ui/BluSettingsActions.kt','utf8');
const home=fs.readFileSync('bluswitch-ui/BluSwitchHomeActivity.kt','utf8');
assert(actions.includes('"data-folder" -> showBluSwitchFolder()'));
assert(!actions.includes('private fun openUserFolder()'), 'Legacy external DocumentsUI route remains');
assert(home.includes('BluSettingsActions(this) { showUserFolder() }'));
assert(home.includes('fun browseUserFiles(path: String)'));
assert(home.includes('fun previewUserFile(path: String)'));
assert(home.includes('this@BluSwitchHomeActivity.previewUserFile(path)'), 'Bridge must call the native preview, not itself');
assert(home.includes('resolveUserFile(relative)'), 'Folder browsing must restrict paths to private data');
let ready;const calls=[],nodes={};
const window={BluNative:new Proxy({}, {get(_t,key){return arg=>calls.push([key,arg]);}})};
const document={getElementById(id){return nodes[id] ||= {textContent:'',innerHTML:''};},addEventListener(kind,fn){if(kind==='DOMContentLoaded')ready=fn;}};
vm.runInNewContext(js,{window,document,setInterval(){},Date,confirm(){return true;},alert(){},console},{filename:'app.js'});
ready();
window.BluSwitch.open('user-files');
window.BluSwitch.setUserFiles(JSON.stringify({path:'',entries:[{name:'config',path:'config',folder:true},{name:'sample.txt',path:'sample.txt',folder:false,size:5}]}));
assert(nodes['main-view'].innerHTML.includes('My BluSwitch 2 Folder'));
assert(nodes['main-view'].innerHTML.includes('config'));
window.BluSwitch.openUserEntry(0);
assert(calls.some(x=>x[0]==='browseUserFiles'&&x[1]==='config'),'Folder navigation must call native browser');
window.BluSwitch.setUserFiles(JSON.stringify({path:'config',entries:[{name:'settings.txt',path:'config/settings.txt',folder:false,size:42}]}));
window.BluSwitch.openUserEntry(0);
assert(calls.some(x=>x[0]==='previewUserFile'&&x[1]==='config/settings.txt'),'File preview must use native bridge');
window.BluSwitch.setUserPreview(JSON.stringify({name:'settings.txt',content:'hello <script>'}));
assert(nodes['main-view'].innerHTML.includes('&lt;script&gt;'),'Text preview must escape HTML');
window.BluSwitch.back();
assert(!nodes['main-view'].innerHTML.includes('hello &lt;script&gt;'));
window.BluSwitch.back();
assert(calls.some(x=>x[0]==='browseUserFiles'&&x[1]===''),'Back must navigate up within folders');
console.log('PASS: BluSwitch in-app folder browser, navigation, preview escaping and no external Eden folder route');
